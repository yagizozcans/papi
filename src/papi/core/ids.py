"""UUIDv7 identifiers (RFC 9562), monotonic within the process.

Layout: 48-bit Unix ms timestamp | version 7 | 12-bit counter (rand_a) | variant | 62 random bits.
Within one millisecond the 12-bit counter is incremented (seeded randomly in the lower half
of its range), so ids generated by this process sort strictly in creation order. Small backward
wall-clock steps (≤ 10 s, e.g. NTP slew) keep the previous timestamp; a larger backward jump resets
to the new clock (ids then no longer sort after the ones minted before the jump).
"""

from __future__ import annotations

import os
import threading
import time
import uuid
from datetime import UTC, datetime

_lock = threading.Lock()
_last_ms = 0
_counter = 0
_COUNTER_MAX = 0xFFF
_MAX_BACKWARD_MS = 10_000


def _seed_counter() -> int:
    return int.from_bytes(os.urandom(2)) & 0x7FF  # leave headroom for increments


def uuid7() -> str:
    """Return a new UUIDv7 as a lowercase canonical string (36 chars)."""
    global _last_ms, _counter
    with _lock:
        ms = time.time_ns() // 1_000_000
        if ms > _last_ms or ms < _last_ms - _MAX_BACKWARD_MS:
            _last_ms = ms
            _counter = _seed_counter()
        else:
            _counter += 1
            if _counter > _COUNTER_MAX:
                _last_ms += 1  # borrow the next millisecond to stay monotonic
                _counter = _seed_counter()
        ms = _last_ms
        counter = _counter
    rand_b = int.from_bytes(os.urandom(8)) & ((1 << 62) - 1)
    value = (ms & ((1 << 48) - 1)) << 80
    value |= 0x7 << 76
    value |= counter << 64
    value |= 0b10 << 62
    value |= rand_b
    return str(uuid.UUID(int=value))


def uuid7_time(value: str) -> datetime:
    """Return the embedded creation time (UTC, ms precision) of a UUIDv7 string."""
    u = uuid.UUID(value)
    if u.version != 7:
        raise ValueError(f"not a UUIDv7: {value}")
    ms = u.int >> 80
    return datetime.fromtimestamp(ms / 1000, tz=UTC)
